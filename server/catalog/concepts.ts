/**
 * 原理题补丁包 —— 给那 75 个「全是计数题」的实验补上真正在考理论的事实。
 *
 * 起因（用户 2026-09-07）：出题面板连着三道都在问「比较了多少次 / 移动了多少次 /
 * 第一趟枢轴是几」。原话：「这种肤浅的实操问题有什么意义？肯定是问理论知识啊。」
 * 根因见 server/catalog.ts 里 FactGenre 那段注释：可核算事实被实现成了 trace 上的计数器。
 *
 * 为什么单独成文件而不是改进原目录：存量 857 条事实散在 4000 行的主表和 8 个分片里，
 * 逐个插入既容易碰坏别人的条目、又没法一眼 review。这里一个实验一段，合并点只有一行
 * （catalog.ts 末尾 attachConcepts）。
 *
 * ── 这里的「焊死」是什么意思 ──
 * 计数题的答案由引擎算；原理题的答案是**我们写死的**，同样不经过大模型 —— 大模型在
 * quiz.ts 里只负责把它改写成一句人话题面，碰不到「哪个是对的」。所以「模型不会答错」这条
 * 依然成立。但要说清楚差别：计数题的答案可由引擎重算验证，原理题不能；原理题的「出处」
 * 取的是这次运行轨迹里的真实一行，只能证明「这一步确实发生过」，不能证明结论本身。
 *
 * 写作纪律（tests/fact-genre.test.ts 在盯着）：
 *   · 干扰项要是**常见错误认知**，不是胡话 —— 胡话选项等于送分；
 *   · 干扰项长度要和正确答案接近 —— 一眼最长的那个是答案，那这题也白出。
 */
import type { Fact } from '../catalog.ts'

type Frame = Record<string, unknown>

/**
 * 造一条原理题。
 * `note` 是这条结论落在轨迹上的哪一步（出处会带上那一步的真实 log），`at` 是取第几帧。
 */
export function cf(id: string, label: string, ask: string, answer: string, wrong: string[], note: string, at = 0): Fact {
  return {
    id, label, ask, kind: 'choice', genre: 'concept',
    compute: (t: Frame[]) => {
      const i = Math.min(at, Math.max(0, t.length - 1))
      const log = String(t[i]?.log ?? '')
      return { answer, step: i, evidence: log ? `${note}（轨迹第 ${i} 步：${log}）` : note }
    },
    distractors: () => wrong,
  }
}
