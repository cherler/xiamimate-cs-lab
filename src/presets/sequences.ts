/**
 * 驱动序列的预置串。
 *
 * 放在引擎侧而不是 registry.ts 里，是因为**每条 note 都是一个关于行为的主张**
 * （"FIFO 在这串上会出现 Belady 异常"、"SSTF 会饿死远端请求"），
 * 而主张必须能被测试验证。放在 .tsx 里测试就 import 不进来。
 *
 * `tests/presets-claims.test.ts` 逐条验这些 note —— 说不出口的就别写在按钮上。
 */
