/** 取某个字段的一行说明；没有就返回 null（名字自己说得清的不给提示）。 */
export function tipFor(label: string): string | null {
  const raw = TIPS[label]
  if (!raw) return null
  if (!raw.startsWith('@')) return raw
  return TERMS.find(t => t.id === raw.slice(1))?.gloss ?? null
}
